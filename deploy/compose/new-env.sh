#!/usr/bin/env bash
# Create a production environment file with unique random secrets.
#
# The file is written with mode 0600 and is never overwritten. No secret is
# printed: the initial administrator password stays in the file.
set -euo pipefail

usage() {
  cat <<'USAGE'
Usage:
  deploy/compose/new-env.sh --domain <host name> --admin-email <email>
                            [--admin-name <name>] [--timezone <IANA zone>]
                            [--release <version>] [--output <path>]

--release uses the published images of that version instead of building
from source, for example --release 0.1.0.

Writes <repository>/.env by default.
USAGE
}

fail() {
  printf 'ERROR: %s\n' "$*" >&2
  exit 1
}

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
output="$(cd "${script_dir}/../.." && pwd)/.env"
domain="" admin_email="" admin_name="Administrator" timezone="UTC" release=""
while [[ $# -gt 0 ]]; do
  [[ $# -ge 2 ]] || { usage; exit 2; }
  case "$1" in
    --domain) domain="$2" ;;
    --admin-email) admin_email="$2" ;;
    --admin-name) admin_name="$2" ;;
    --timezone) timezone="$2" ;;
    --release) release="${2#v}" ;;
    --output) output="$2" ;;
    *) usage; exit 2 ;;
  esac
  shift 2
done
[[ -n "${domain}" && -n "${admin_email}" ]] || { usage; exit 2; }
[[ "${domain}" =~ ^[A-Za-z0-9.-]+$ ]] || fail "--domain must be a host name such as bi.example.com"
[[ "${admin_email}" == *@*.* ]] || fail "--admin-email must be an email address"
[[ "${admin_name}" != *$'\n'* ]] || fail "--admin-name must be one line"
[[ -z "${release}" || "${release}" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || fail "--release must be a version such as 0.1.0"
[[ ! -e "${output}" ]] || fail "${output} already exists; move it away first"
command -v openssl >/dev/null || fail "openssl is required"

hex() { openssl rand -hex "$1"; }
# One API process per core, leaving one core for the worker, database, and gateway.
cores="$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 2)"
api_workers=$(( cores > 4 ? 4 : (cores > 1 ? cores - 1 : 1) ))
# URL-safe base64 of exactly 32 random bytes, without padding.
encryption_key() { openssl rand -base64 32 | tr '+/' '-_' | tr -d '=\n'; }

umask 077
cat >"${output}.partial" <<ENV
# Generated by deploy/compose/new-env.sh on $(date -u +%Y-%m-%d).
# Keep this file private and store a copy separately from backups: without
# DATAPIPETTE_CONNECTION_ENCRYPTION_KEY saved source passwords cannot be read.
DATAPIPETTE_DOMAIN=${domain}
DATAPIPETTE_INSTALLATION_TIMEZONE=${timezone}
DATAPIPETTE_API_WORKERS=${api_workers}
DATAPIPETTE_BOOTSTRAP_ADMIN_EMAIL=${admin_email}
DATAPIPETTE_BOOTSTRAP_ADMIN_DISPLAY_NAME="${admin_name}"
DATAPIPETTE_BOOTSTRAP_ADMIN_PASSWORD=$(hex 18)
DATAPIPETTE_POSTGRES_PASSWORD=$(hex 32)
DATAPIPETTE_S3_ACCESS_KEY_ID=datapipette-$(hex 6)
DATAPIPETTE_S3_SECRET_ACCESS_KEY=$(hex 32)
DATAPIPETTE_CONNECTION_ENCRYPTION_KEY=$(encryption_key)
ENV
if [[ -n "${release}" ]]; then
  cat >>"${output}.partial" <<ENV
DATAPIPETTE_BACKEND_IMAGE=ghcr.io/weagook/datapipette-backend
DATAPIPETTE_FRONTEND_IMAGE=ghcr.io/weagook/datapipette-frontend
DATAPIPETTE_IMAGE_TAG=${release}
ENV
fi
mv "${output}.partial" "${output}"
printf 'Wrote %s (mode 600).\n' "${output}"
printf 'The first administrator signs in as %s with DATAPIPETTE_BOOTSTRAP_ADMIN_PASSWORD from that file.\n' "${admin_email}"
