interface I18nValue {
  locale: InterfaceLocale;
  setLocale: (locale: InterfaceLocale) => void;
  t: (message: string, replacements?: Replacements) => string;
}

const defaultValue: I18nValue = {
  locale: "en",
  setLocale: () => undefined,
  t: interpolate,
};

const I18nContext = createContext<I18nValue>(defaultValue);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<InterfaceLocale>("en");
  const t = useCallback(
    (message: string, replacements?: Replacements) =>
      interpolate(locale === "ru" ? translateRussian(message) : message, replacements),
    [locale],
  );
  const value = useMemo(() => ({ locale, setLocale, t }), [locale, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}

function interpolate(message: string, replacements: Replacements = {}): string {
  return message.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.hasOwn(replacements, key) ? String(replacements[key]) : match,
  );
}

function translateRussian(message: string): string {
  const exact = russian[message];
  if (exact) return exact;
  const patterns: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
    [/^Enter (.+)$/u, (match) => `Введите ${match[1]}`],
    [/^(.+) needs at least one value\.$/u, (match) => `${match[1]}: укажите хотя бы одно значение.`],
    [/^(.+) accepts at most 100 values\.$/u, (match) => `${match[1]}: допускается не более 100 значений.`],
    [/^(.+) needs both ends of the range\.$/u, (match) => `${match[1]}: укажите обе границы диапазона.`],
    [/^(.+) needs a value\.$/u, (match) => `${match[1]}: укажите значение.`],
    [/^(.+) accepts only true or false\.$/u, (match) => `${match[1]}: допустимо только true или false.`],
    [/^(.+) needs a whole number\.$/u, (match) => `${match[1]}: укажите целое число.`],
    [/^(.+) needs a valid number\.$/u, (match) => `${match[1]}: укажите корректное число.`],
    [/^Use (.+)–(.+)$/u, (match) => `Допустимый диапазон: ${match[1]}–${match[2]}`],
    [/^Use a value above (.+) and up to (.+)$/u, (match) => `Укажите значение больше ${match[1]} и не выше ${match[2]}`],
  ];
  for (const [pattern, render] of patterns) {
    const match = message.match(pattern);
    if (match) return render(match);
  }
  return message;
}
